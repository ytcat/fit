'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const T = require('../assets/vendor/three.min.js');
const src = fs.readFileSync(path.join(__dirname,'../adventure/free-walk/free-walk-town.js'), 'utf8');
assert.doesNotMatch(src,/new T\.PointLight|lamp\.position\.set/,'no warm point light follows the avatar');
const a = src.indexOf('function streetLampPools'), b = src.indexOf('\n  /** Fine grain',a);
assert.ok(a>=0 && b>a, 'ground pool helper present');
const build = vm.runInNewContext('(' + src.slice(a,b) + ')',{CELL:.5,S:3});
const lamp = {x:0,y:.4,z:0,ry:Math.PI/2}, meshes = h => build(T, [lamp], h, x=>x);
const clear = meshes(()=>1.2);
const wall = meshes((x,z)=>x>=3&&x<3.5?6:1.2);
const p = o => o.geometry.attributes.position;
assert.equal(p(clear).count / 3,32);
assert.ok(Array.from(p(clear).array).every(Number.isFinite));
const maxX = o => Math.max(...Array.from({length:p(o).count},(_,i)=>p(o).getX(i)));
assert.ok(maxX(clear)>6,'open sidewalk has full reach');
assert.ok(maxX(wall)<3,'wall stops the light, including the ground beyond it');
assert.ok(Array.from({length:p(wall).count},(_,i)=>p(wall).getY(i)).every(y=>Math.abs(y-1.218)<.01),'light mesh stays at pavement height');
assert.ok(clear.material.depthTest && !clear.material.depthWrite);
assert.match(clear.material.fragmentShader,/smoothstep\(0\.0, 1\.0, length\(vPool\)\)/);
assert.ok(meshes(()=>.02)===null,'no floating or water pool');
console.log('PASS street lamp pools: bounded falloff, pavement-only and no spill behind the wall');
